"""Minimal LLM client for the chat demo.

Wraps the Volcengine Ark (OpenAI-compatible) endpoint and exposes a single
agent helper that turns a user question into a ``get_financial_metric()`` call
and then asks the model to narrate the result in Chinese.

The LLM only ever produces query *parameters*; the actual PostgreSQL read is
always performed by the existing ``financial_query`` service, so no SQL is ever
generated by the model.
"""
from __future__ import annotations

import json
import os
import sys
from functools import lru_cache
from pathlib import Path
from typing import Any

# Ensure the repo root (containing ontology/ and financial_query/) is importable.
_ROOT = Path(__file__).resolve().parents[1]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

# Load the demo credentials (ARK_*) and the ETL connection string (AI_POSTGRES_URL).
try:
    from dotenv import load_dotenv
    load_dotenv(_ROOT / "chat" / ".env", override=False)
    load_dotenv(_ROOT / "data_etl" / ".env", override=False)
except Exception:
    pass

from openai import OpenAI

from financial_query import get_financial_metric
from ontology import Ontology

# Default trial data (Phase 4 fixed test bank/date).
_DEFAULT_BANK_ID = -48858
_DEFAULT_AS_OF = "2026-06-30"

_CLIENT = OpenAI(
    base_url=os.getenv("ARK_BASE_URL", "https://ark.cn-beijing.volces.com/api/v3"),
    api_key=os.getenv("ARK_API_KEY", ""),
)
_MODEL = os.getenv("ARK_MODEL", "glm-5-3-flash-260828")


@lru_cache(maxsize=1)
def _valid_concept_ids() -> tuple[str, ...]:
    return tuple(sorted(Ontology.load().concept_ids))


_TOOL = {
    "type": "function",
    "function": {
        "name": "get_financial_metric",
        "description": (
            "Query a bank financial metric by Ontology Concept ID. Only call "
            "this when the user clearly refers to one of the supported "
            "financial concepts for a given bank and date."
        ),
        "parameters": {
            "type": "object",
            "properties": {
                "concept_id": {
                    "type": "string",
                    "enum": list(_valid_concept_ids()),
                    "description": "Ontology Concept ID, e.g. ALM.NII.BASE",
                },
                "bank_id": {
                    "type": "integer",
                    "description": f"Bank identifier (default {_DEFAULT_BANK_ID})",
                },
                "as_of_date": {
                    "type": "string",
                    "description": f"As-of date YYYY-MM-DD (default {_DEFAULT_AS_OF})",
                },
            },
            "required": ["concept_id"],
        },
    },
}


def _normalize_args(args: dict[str, Any]) -> dict[str, Any]:
    concept_id = args.get("concept_id")
    if concept_id not in _valid_concept_ids():
        raise ValueError(f"unsupported concept_id: {concept_id!r}")
    bank_id = int(args.get("bank_id", _DEFAULT_BANK_ID))
    as_of_date = str(args.get("as_of_date") or _DEFAULT_AS_OF)
    return {"concept_id": concept_id, "bank_id": bank_id, "as_of_date": as_of_date}


def _to_jsonable(result: Any) -> dict:
    from decimal import Decimal
    data = {
        "status": result.status.value,
        "concept_id": result.concept_id,
        "concept_name": result.concept_name,
        "bank_id": result.bank_id,
        "as_of_date": result.as_of_date,
        "scenario": result.scenario,
        "source": result.source,
        "definition_status": result.definition_status,
        "message": result.message,
    }
    data["value"] = str(result.value) if isinstance(result.value, Decimal) else result.value
    return data


def run_agent(user_message: str, history: list[dict] | None = None) -> dict:
    """Run one chat turn: extract params -> call service -> narrate.

    Returns ``{"reply": str, "calls": [ {request, result}, ... ]}``.
    """
    history = history or []
    messages = [
        {
            "role": "system",
            "content": (
                "You are the conversational assistant for the ALMAI bank financial "
                "data platform. Users ask in natural language about bank financial "
                "metrics (e.g. Base NII, U200 NII, EVE, ROA, Tier1 capital). When you "
                "can determine which metric, which bank, and which date the user means, "
                "call the get_financial_metric tool to query; otherwise ask the user to "
                "clarify the missing information. After retrieving a result, reply in "
                "concise English and explain the metric meaning, value, scenario, and "
                "data source."
            ),
        }
    ]
    for turn in history:
        messages.append({"role": turn.get("role", "user"), "content": turn.get("content", "")})
    messages.append({"role": "user", "content": user_message})

    calls: list[dict] = []
    resp = _CLIENT.chat.completions.create(
        model=_MODEL, messages=messages, tools=[_TOOL], tool_choice="auto"
    )
    msg = resp.choices[0].message

    if msg.tool_calls:
        messages.append(msg)  # assistant turn carrying tool_calls
        for tc in msg.tool_calls:
            try:
                args = json.loads(tc.function.arguments or "{}")
                params = _normalize_args(args)
            except Exception as exc:  # invalid params -> surface as a tool error
                messages.append({
                    "role": "tool", "tool_call_id": tc.id,
                    "content": json.dumps({"error": str(exc)}, ensure_ascii=False),
                })
                continue
            result = _to_jsonable(get_financial_metric(**params))
            calls.append({"request": params, "result": result})
            messages.append({
                "role": "tool", "tool_call_id": tc.id,
                "content": json.dumps(result, ensure_ascii=False),
            })
        follow = _CLIENT.chat.completions.create(model=_MODEL, messages=messages)
        reply = follow.choices[0].message.content or ""
    else:
        # Model chose not to call the tool (e.g. small talk or a clarifying question).
        reply = msg.content or ""

    return {"reply": reply, "calls": calls}

